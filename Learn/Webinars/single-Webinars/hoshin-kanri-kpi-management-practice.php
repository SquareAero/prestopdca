<script>


document.addEventListener("DOMContentLoaded", function () {

    const wrappers = document.querySelectorAll('.webinar-video-wrapper');

    wrappers.forEach((wrapper, index) => {

        const openBtn = wrapper.querySelector('.open-form-btn');
        const popup = wrapper.parentElement.querySelector('.webinar-popup');
        const closeBtn = popup.querySelector('.close-popup');

        const nameInput = popup.querySelector('.name');
        const emailInput = popup.querySelector('.email');
        const submitBtn = popup.querySelector('.submitForm');

        const nameError = popup.querySelector('.error-name');
        const emailError = popup.querySelector('.error-email');

        // ✅ Check unlock
        if (localStorage.getItem('videoUnlocked_' + index) === 'true') {
            wrapper.classList.remove('is-locked');
            openBtn.style.display = "none";
        }

        // OPEN
        openBtn.addEventListener('click', () => {
            popup.classList.add('active');
            document.body.style.overflow = "hidden";
        });

        // CLOSE
        closeBtn.addEventListener('click', () => {
            popup.classList.remove('active');
            document.body.style.overflow = "auto";
        });

        // VALIDATION
        function validateForm() {
            let valid = true;
            const name = nameInput.value.trim();
            const email = emailInput.value.trim();

            const emailPattern = /^[^ ]+@[^ ]+\.[a-z]{2,3}$/;

            if (!name || name.length < 3) {
                nameError.style.display = "block";
                nameError.innerText = "Enter valid name (min 3 chars)";
                valid = false;
            } else {
                nameError.style.display = "none";
            }

            if (!email || !email.match(emailPattern)) {
                emailError.style.display = "block";
                emailError.innerText = "Enter valid email";
                valid = false;
            } else {
                emailError.style.display = "none";
            }

            return valid;
        }

        // SUBMIT
        submitBtn.addEventListener('click', function (e) {

            e.preventDefault();

            if (!validateForm()) return;

            fetch('https://www.prestopdca.com/wp-admin/admin-ajax.php', {
                method: 'POST',
                headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
                body: new URLSearchParams({
                    action: 'save_webinar_form',
                    name: nameInput.value,
                    email: emailInput.value
                })
            })
            .then(res => res.json())
            .then(data => {

                if (data.success) {

                    localStorage.setItem('videoUnlocked_' + index, 'true');

                    wrapper.classList.remove('is-locked');
                    popup.classList.remove('active');
                    openBtn.style.display = "none";

                    document.body.style.overflow = "auto";
                }

            });

        });

    });

});
</script>



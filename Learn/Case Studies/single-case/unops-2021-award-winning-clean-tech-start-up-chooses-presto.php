<h4 id="summary" class="wp-block-heading">Summary</h4>
<p>Since October of 2020 we have been supporting Avsalt, Sweden’s newest clean water &amp; sanitation Startup who was recently awarded by the&nbsp;<a href="https://www.unops.org/" target="_blank" rel="noreferrer noopener">United Nations Office for Projects &amp; Services (UNOPS)</a>&nbsp;a spot in their 2021 boot camp program together with 4 other start-ups.</p>
<p>Being a clean tech Startup, Avsalt has successfully completed the prototype phase, received 2 rounds of seed funding and is now entering the ‘scale up’ phase of its life cycle, a phase where unexpected challenges can often step in the way of the endless number of deliverables and projects already committed to its stakeholders.</p>
<p>Avsalt CEO Svein Erik Sogn was looking for a solution to support strategy deployment, performance governance and daily discipline in handling all planned and unplanned tasks.</p>
<p>Since the commencement last autumn, we have been partnering with avsalt’s C-suite as a startup mentor assisting in the framing of roles and responsibilities of the present team, cataloguing Avsalt processes, assigning accountability, and mapping outstanding activities to the mid-term and long term growth strategy.</p>
<p>Leveraging our business management system PRESTO Digital Enterprise, the Avsalt leadership team has been able to articulate their long-term strategy in investor and client presentations while developing a daily discipline among the team to manage tasks and make tactical decisions based on urgency.</p>
